/**
 * 写作类型插件：新闻写作。
 *
 * 这是一行独立的 Cordis 插件，可以单独停用。
 *
 * @module dsh-writing-canvas/types/news
 */

import { registerType } from './registry.js';

/** Cordis 插件名。 */
export const name = 'writing-type-news';

/**
 * @param ctx - Cordis 上下文。
 */
export function apply(ctx) {
  ctx.effect(
    () =>
      registerType({
        id: 'news',
        label: '新闻写作',
        order: 50,
        summary: '消息、通讯，重事实核查与来源可追溯',
        format: { kind: 'markdown' },
        mustConfirm: ['报道体裁（消息 / 通讯 / 特写）', '发布媒体与受众', '可获取的信源', '是否已有采访素材'],
        constraints: [
          '严格遵守倒金字塔：最重要的事实放导语，其后按重要性递减排列。',
          '导语必须回答何时、何地、何人、何事，并尽可能包含何因与如何。',
          '事实与观点必须分离。观点只能以引语形式出现，且必须注明说话人身份。',
          '所有引语、数据、机构名称必须有明确来源。无法核实的必须在文中写明"尚未获得证实"。',
          '禁用评价性形容词（圆满成功、高度重视、反响热烈）。改用可核查的事实描述。',
          '人名、职务、机构名称首次出现必须使用全称。',
          '禁止把传闻或单一匿名信源作为唯一依据。',
          '未实际获取的信息不得写入正文。信息不足时必须明确告知还缺什么，不得推测填补。',
        ],
        structure: ['标题', '导语：核心事实', '次导语：补充细节', '主体：按重要性递减', '背景', '引语与来源'],
        checklist: [
          '导语是否回答了何时、何地、何人、何事？',
          '是否严格遵守倒金字塔？',
          '观点是否全部以注明身份的引语形式出现？',
          '每个数据与引语是否都有来源？',
          '是否出现评价性形容词？',
          '人名与机构名首次出现是否为全称？',
          '是否存在未经核实即写入的内容？',
        ],
      }),
    'writing-type-news: 注册新闻写作类型',
  );
}
