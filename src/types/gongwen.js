/**
 * 写作类型插件：公文写作。
 *
 * 这是一行独立的 Cordis 插件，可以单独停用。
 * 默认格式规格为受约束 DOCX（GB/T 9704 版式：字体、字号、行距、页边距均由
 * 格式引擎真实写入并对产物回读校验）。
 *
 * @module dsh-writing-canvas/types/gongwen
 */

import { registerType } from './registry.js';

/** Cordis 插件名。 */
export const name = 'writing-type-gongwen';

/**
 * @param ctx - Cordis 上下文。
 */
export function apply(ctx) {
  ctx.effect(
    () =>
      registerType({
        id: 'gongwen',
        label: '公文写作',
        order: 20,
        summary: '党政机关公文，版式与结构受规范约束',
        format: { kind: 'docx', spec: 'gongwen-gb9704' },
        mustConfirm: ['发文机关', '文种（通知 / 请示 / 报告 / 函 / 纪要…）', '主送机关', '成文日期', '是否涉及其他部门职权'],
        constraints: [
          '文种必须与行文目的匹配：请示用于请求批准，报告用于汇报工作，通知用于告知或部署。禁止混用或以"报告"夹带请示事项。',
          '一文一事：一份公文只处理一个事项。',
          '不得越级行文。确需越级的，必须说明理由并同时抄送被越过的机关。',
          '结构层次序数依次使用"一、""（一）""1.""（1）"，不得跳级、不得混用。',
          '数字用法：成文日期、发文字号、层次序数用阿拉伯数字；概数与习惯用语用汉字。',
          '禁止夸张、抒情、比喻等文学化表达；不使用"我们认为""大概""可能是"等不确定表述。',
          '引用其他文件必须先引标题、后引发文字号，并用圆括号标注。',
          '涉及其他部门职权的事项，必须先行协商并在文中注明会签情况。',
          '本类型默认使用 DOCX。字体、字号、行距必须由格式工具真实写入文件并对产物回读校验，禁止仅在回复中声称已按要求排版。',
        ],
        structure: [
          '标题：发文机关 + 事由 + 文种',
          '主送机关',
          '正文 · 缘由',
          '正文 · 事项',
          '正文 · 结语',
          '附件说明',
          '发文机关署名',
          '成文日期',
        ],
        checklist: [
          '文种是否与行文目的完全一致？',
          '是否做到一文一事？',
          '层次序数是否规范、是否跳级？',
          '数字用法是否正确？',
          '是否存在文学化或不确定表述？',
          '引用文件是否先标题后字号？',
          '附件说明与正文提及的附件是否一致？',
          '发文机关署名与成文日期是否齐全？',
        ],
      }),
    'writing-type-gongwen: 注册公文写作类型',
  );
}
